// Aircraft helpers shared by the page and the server (alerts), so both read "mil" or "beluga" alike.
import TYPES from "./types.json"; // generated by scripts/update-types.ts

// the readsb fields this app reads
export type Aircraft = {
  hex: string;
  flight?: string;
  r?: string;
  t?: string;
  desc?: string;
  dbFlags?: number;
  category?: string; // ADS-B emitter category: A1 light .. A5 heavy, A6 high performance, A7 rotorcraft, B*, C*
  lat?: number;
  lon?: number;
  alt_baro?: number | "ground";
  gs?: number;
  track?: number;
};

// names people search for -> ICAO type designators
export const ALIASES: Record<string, string> = {
  beluga: "A3ST A337", // A300-600ST Beluga, A330-743L BelugaXL
  a380: "A388",
  "747": "B741 B742 B743 B744 B748 B74S",
  dreamliner: "B788 B789 B78X",
  concorde: "CONC",
};

const words = (text: string) => text.toLowerCase().split(/[\s,]+/).filter(Boolean);

export const filterTerms = (text: string) => words(text).flatMap((t) => (ALIASES[t] ?? t).toLowerCase().split(" "));

// terms that look like a full ICAO type designator (A3ST, B748, C172) get a worldwide lookup;
// a digit is required so airline prefixes like DLH don't trigger one, aliases (CONC) always do
export function globalTypes(text: string) {
  const fromAlias = words(text).flatMap((t) => ALIASES[t]?.toLowerCase().split(" ") ?? []);
  return [...new Set(filterTerms(text).filter((t) => fromAlias.includes(t) || /^(?=.*\d)[a-z0-9]{3,4}$/.test(t)))];
}

export type AircraftClass =
  | "heavy" | "airliner" | "bizjet" | "fighter" | "turboprop" | "single" | "twin"
  | "heli" | "glider" | "balloon" | "drone" | "ground" | "unknown";

// fast jets whose ICAO description (L2J, medium) would otherwise read as an airliner
const FIGHTERS = new Set(["EUFI", "F15", "F16", "F18H", "F18S", "F22", "F35", "RFAL", "TOR", "MIR2", "F5", "A10", "T38", "HAWK", "M346", "L159", "AJET", "JAS39", "SU27", "MG29"]);
const TYPE_TABLE = TYPES as Record<string, [string, string]>;

// type designator via its ICAO description (L2J = landplane, 2 engines, jet) and wake category,
// falling back to the ADS-B emitter category the transponder sends; same idea as tar1090's markers.js
export function classify(a: Aircraft): AircraftClass {
  const cat = a.category ?? "";
  if (/^C[1-3]$/.test(cat)) return "ground";
  if (cat === "B6") return "drone";
  if (cat === "B2") return "balloon";

  const [desc, wtc] = TYPE_TABLE[a.t ?? ""] ?? [];
  if (desc) {
    const [kind, engines, engine] = desc;
    if (FIGHTERS.has(a.t!) || cat === "A6") return "fighter";
    if (kind === "H" || kind === "G") return "heli";
    if (kind === "B") return "balloon";
    if (kind === "D") return "drone";
    if (kind === "V") return "ground";
    if (kind === "P" || engines === "0" || engine === "M") return "glider";
    if (engine === "J") {
      if (wtc === "H" || wtc === "J") return "heavy";
      // wake "medium" spans 7-136 t, Phenom to A321; the transponder's A1/A2 (< 34 t) splits off business jets
      return wtc === "L" || cat === "A1" || cat === "A2" ? "bizjet" : "airliner";
    }
    if (engine === "T") return "turboprop"; // incl. tiltrotors (R2T)
    return engines === "1" ? "single" : "twin";
  }
  return ({ A1: "single", A2: "bizjet", A3: "airliner", A4: "airliner", A5: "heavy", A6: "fighter", A7: "heli", B1: "glider", B4: "single" } as Record<string, AircraftClass>)[cat] ?? "unknown";
}

// filter words for classes; "jet" and "prop" group several
const CLASS_TERMS: Record<string, AircraftClass[]> = {
  heavy: ["heavy"], airliner: ["airliner"], bizjet: ["bizjet"], fighter: ["fighter"], turboprop: ["turboprop"],
  single: ["single"], twin: ["twin"], heli: ["heli"], glider: ["glider"], balloon: ["balloon"], drone: ["drone"], ground: ["ground"],
  jet: ["heavy", "airliner", "bizjet", "fighter"],
  prop: ["turboprop", "single", "twin"],
};

// filter text -> predicate: any term is a substring of callsign, registration, type or description;
// "mil" matches airframes the readsb database flags as military (dbFlags bit 0); class words match classify()
export function matcher(text: string): (a: Aircraft) => boolean {
  const terms = filterTerms(text);
  if (!terms.length) return () => true;
  return (a) => {
    const hay = [a.flight, a.r, a.t, a.desc].filter(Boolean).join(" ").toLowerCase();
    return terms.some((t) => {
      if (t === "mil") return ((a.dbFlags ?? 0) & 1) === 1;
      if (CLASS_TERMS[t]) return CLASS_TERMS[t].includes(classify(a));
      return hay.includes(t);
    });
  };
}

export const callsign = (a: Aircraft) => (a.flight ?? "").trim() || a.r || a.hex.toUpperCase();

// Data comes in aviation units (nm, kt, ft, ft/min); "metric" only changes how it is shown.
export type Units = "imperial" | "metric";
export const KM_PER_NM = 1.852;
const M_PER_FT = 0.3048;

export const toUnit = (nm: number, units: Units) => (units === "metric" ? nm * KM_PER_NM : nm);

export const distText = (nm: number, units: Units, digits = 1) =>
  `${toUnit(nm, units).toFixed(digits)} ${units === "metric" ? "km" : "nm"}`;

export const speedText = (kt: number | undefined, units: Units) =>
  kt == null ? "-" : units === "metric" ? `${Math.round(kt * KM_PER_NM)} km/h` : `${Math.round(kt)} kt`;

export const climbText = (fpm: number | undefined, units: Units) =>
  fpm == null ? "-" : units === "metric" ? `${((fpm * M_PER_FT) / 60).toFixed(1)} m/s` : `${fpm} ft/min`;

// imperial: FL above 10,000 ft; metric: always whole metres
export function altText(a: Aircraft, units: Units = "imperial") {
  if (a.alt_baro === "ground") return "GND";
  if (a.alt_baro == null) return "-";
  if (units === "metric") return `${Math.round(a.alt_baro * M_PER_FT)} m`;
  return a.alt_baro >= 10000 ? `FL${Math.round(a.alt_baro / 100)}` : `${a.alt_baro} ft`;
}

// distance (nm) and bearing (degrees true) from a point to an aircraft
// ponytail: flat-earth projection, a few % off beyond ~300 nm
export function relative(from: { lat: number; lon: number }, a: { lat: number; lon: number }) {
  const east = ((((a.lon - from.lon + 180) % 360) + 360) % 360 - 180) * 60 * Math.cos((from.lat * Math.PI) / 180);
  const north = (a.lat - from.lat) * 60;
  return { dist: Math.hypot(east, north), bearing: ((Math.atan2(east, north) * 180) / Math.PI + 360) % 360 };
}
